// Turns moves.js into Packages/OMMKit/Sources/OMMKit/HowToMoves.swift.
// Run from anywhere: node OMM/tools/howto/generate.js
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const here = __dirname;
const sandbox = { globalThis: {} };
sandbox.globalThis = sandbox;
vm.runInNewContext(fs.readFileSync(path.join(here, "moves.js"), "utf8"), sandbox);
const data = sandbox.HOWTO;
const out = path.join(here, "..", "..", "Packages", "OMMKit", "Sources", "OMMKit", "HowToMoves.swift");

const num = n => {
  if (typeof n !== "number" || !isFinite(n)) throw new Error("Bad number: " + n);
  return String(Math.round(n * 10) / 10);
};
const pt = p => `HowToPoint(${num(p[0])}, ${num(p[1])})`;
const str = s => JSON.stringify(s);

function pose(p) {
  const parts = [`hip: ${pt(p.hip)}`, `shoulder: ${pt(p.sh)}`, `nearHand: ${pt(p.nh)}`, `farHand: ${pt(p.fh)}`,
                 `nearFoot: ${pt(p.nf)}`, `farFoot: ${pt(p.ff)}`];
  if (p.sw) parts.push(`shoulderHalf: ${pt(p.sw)}`);
  if (p.hw) parts.push(`hipHalf: ${pt(p.hw)}`);
  if (p.ht) parts.push(`headTurn: ${num(p.ht)}`);
  if (p.hideBody) parts.push(`hideBody: true`);
  return `HowToPose(${parts.join(", ")})`;
}

function prop(pr) {
  switch (pr.k) {
    case "bench": return `.bench(x: ${num(pr.x)}, y: ${num(pr.y)}, width: ${num(pr.w)})`;
    case "seat": return `.seat(x: ${num(pr.x)}, y: ${num(pr.y)}, width: ${num(pr.w)}, backTop: ${num(pr.back)})`;
    case "tower": return `.tower(x: ${num(pr.x)}, top: ${num(pr.top)})`;
    case "cable": return `.cable(from: ${pt(pr.from)}, nearHand: ${pr.hand !== "f"})`;
    case "lever": return `.lever(pivot: ${pt(pr.pivot)}, postX: ${num(pr.post)})`;
    case "barbell": return ".barbell";
    case "dumbbells": return ".dumbbells";
    case "squeeze": return ".squeeze";
    default: throw new Error("Unknown prop " + pr.k);
  }
}

function move(m) {
  const [na, fa, nl, fl] = m.bends;
  const frames = m.frames.map(f => `                HowToFrame(${pose(f.p)},\n                           hold: ${num(f.hold)}, move: ${num(f.go)}),`).join("\n");
  return `        HowToMove(
            exercise: ${str(m.name)},
            view: .${m.view},
            bends: HowToMove.Bends(nearArm: ${na}, farArm: ${fa}, nearLeg: ${nl}, farLeg: ${fl}),
            props: [${(m.props || []).map(prop).join(", ")}],
            frames: [
${frames}
            ],
            tips: [
${m.tips.map(t => `                ${str(t)},`).join("\n")}
            ]),`;
}

const swift = `// Generated by OMM/tools/howto/generate.js from moves.js. Don't edit by hand:
// change moves.js, check it in preview.html, then run the generator again.

extension HowTo {
    /// Group key → animated exercises.
    static let drawn: [String: [HowToMove]] = [
        ${str(data.group)}: [
${data.moves.map(m => move(m).replace(/^/gm, "    ")).join("\n")}
        ],
    ]
}
`;
fs.writeFileSync(out, swift);
console.log(`Wrote ${data.moves.length} moves for ${data.group} to ${path.relative(process.cwd(), out)}`);
