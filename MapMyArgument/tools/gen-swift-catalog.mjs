// Writes Packages/ArgumentKit/Sources/ArgumentKit/Catalog.swift from web/js/catalog.js,
// so both apps share the same topics and example maps.
//   node MapMyArgument/tools/gen-swift-catalog.mjs
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
const C = require(join(here, "../web/js/catalog.js"));

const swiftString = (s) => JSON.stringify(s); // JSON string escapes are valid Swift escapes for this text
const raw = (obj) => {
  const json = JSON.stringify(obj);
  if (json.includes('"#')) throw new Error("JSON contains \"#, which would end the raw string");
  return '#"' + json + '"#';
};

let out = `// Generated by tools/gen-swift-catalog.mjs from web/js/catalog.js. Do not edit by hand.
import Foundation

public enum Catalog {
    public struct TopicGroup: Identifiable, Sendable {
        public var id: String { category }
        public let category: String
        public let items: [String]
    }

    public static let topics: [TopicGroup] = [
`;
for (const g of C.TOPICS) {
  out += `        TopicGroup(category: ${swiftString(g.category)}, items: [\n`;
  for (const t of g.items) out += `            ${swiftString(t)},\n`;
  out += `        ]),\n`;
}
out += `    ]

    /// The example on the home screen: a nuclear power argument with the usual soft spots.
    public static let example: ArgumentMap = decode(exampleJSON)

    /// Sam's rating of the example, for the example comparison.
    public static let exampleFriend: ArgumentMap = decode(exampleFriendJSON)

    static func decode(_ json: String) -> ArgumentMap {
        (try? JSONDecoder().decode(ArgumentMap.self, from: Data(json.utf8))) ?? ArgumentMap()
    }

    static let exampleJSON = ${raw(C.EXAMPLE)}

    static let exampleFriendJSON = ${raw(C.EXAMPLE_FRIEND)}
}
`;
const target = join(here, "../Packages/ArgumentKit/Sources/ArgumentKit/Catalog.swift");
writeFileSync(target, out);
console.log("Wrote", target);
